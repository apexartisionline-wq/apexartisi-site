import { vocative } from "./vocative";

// Email για νέο μήνυμα της ομάδας (υπεύθυνη 22/10: «και μετά θα πηγαίνει και σε email»). ΟΥΔΕΤΕΡΟ: χωρίς το κείμενο του
// μηνύματος και χωρίς λέξεις για πρόγραμμα/ανάκαμψη — το Gmail του προγράμματος δεν έχει σύμβαση επεξεργασίας (mail.ts) και
// το email μπορεί να το δει κι άλλος. Το μήνυμα διαβάζεται μόνο μέσα στο Apex. Διατύπωση προς έγκριση.
export function teamMessageEmail(p: { name: string; url: string; appName?: string }): { subject: string; text: string } {
  const first = vocative(p.name.trim().split(/\s+/)[0] || p.name);
  const app = p.appName || "Apex";
  return {
    subject: `${app} — ένα μήνυμα για σένα`,
    text: [
      `Γεια σου, ${first}.`,
      ``,
      `Σου στείλαμε ένα μήνυμα στο ${app}. Μπες για να το διαβάσεις:`,
      p.url,
      ``,
      `Για τη δική σου ασφάλεια, το μήνυμα φαίνεται μόνο μέσα στο ${app}, όχι στο email.`,
      ``,
      `Η ομάδα του ${app}`,
    ].join("\n"),
  };
}

/** Το μήνυμα ολοκλήρωσης κύκλου: θετικό πρόσημο, χωρίς μετρήματα και χωρίς χρέωση (απόφαση 20/10). Διατύπωση προς έγκριση. */
export function cycleDoneText(name: string): string {
  return [
    `${vocative(name.trim().split(/\s+/)[0] || name)}, ολοκλήρωσες τον κύκλο σου.`,
    "Ατομικές και ομάδες, μία μέρα τη φορά — τα κατάφερες.",
    "Σύντομα θα σου γράψουμε τι είδαμε. Η ομάδα σου είναι εδώ για τη συνέχεια.",
    "Η ομάδα του Apex",
  ].join("\n\n");
}
