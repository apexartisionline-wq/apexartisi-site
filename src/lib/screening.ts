export type ScreenScore = { score: number; answered: number; of: number; band: string; level: "plain" };
export const HEAVY_USE_BAND = "περίοδος βαριάς χρήσης · ενδεικτικός αριθμός";

export function screenScore(a: (number | null)[] | undefined): ScreenScore | null {
  const xs = (a ?? []).filter((x): x is number => x !== null && x !== undefined);
  if (xs.length === 0) return null;
  return { score: xs.reduce((s, x) => s + x, 0), answered: xs.length, of: 10, band: HEAVY_USE_BAND, level: "plain" };
}

