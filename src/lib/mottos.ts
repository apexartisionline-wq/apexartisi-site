/** Το μότο της ημέρας (ώρα Ελλάδας, YYYY-MM-DD): ίδιο για όλους την ίδια μέρα, διαφορετικό την επόμενη. */
export function mottoFor(date: string): string {
  const [y, m, d] = date.split("-").map(Number);
  const days = Math.floor(Date.UTC(y, (m || 1) - 1, d || 1) / 86_400_000);
  return MOTTOS[((days % MOTTOS.length) + MOTTOS.length) % MOTTOS.length];
}
