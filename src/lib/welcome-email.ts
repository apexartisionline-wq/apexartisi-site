// Email καλωσορίσματος σε νέο μέλος (υπεύθυνη 16/10: «φεύγει email που τον καλωσορίζει, του δίνει κωδικούς, και
// ό,τι άλλο είναι σωστό να στέλνει»). Μόνο κείμενο, με τις «Λέξεις προς το μέλος» (ατομική, η ομάδα σου, το Apex, το «Σήμερα»).
// Τι μπαίνει και γιατί (καλή πρακτική για email σε νέο μέλος υπηρεσίας ψυχικής υγείας — όχι κλινικό περιεχόμενο):
//   1. καλωσόρισμα με το όνομα · 2. πού μπαίνει, όνομα χρήστη, κωδικός (απόφαση 16/10: ο κωδικός μέσα στο email) και ότι
//   τον αλλάζει στην πρώτη είσοδο · 3. τα πρώτα βήματα (στοιχεία πριν την 1η ατομική, ομάδες, ημερολόγιο) · 4. ποιος βλέπει τι
//   (ΓΚΠΔ άρθρο 13: ενημέρωση τη στιγμή της συλλογής — εδώ σύντομα, η πλήρης ενημέρωση δίνεται στη Σ0) · 5. ασφάλεια: 112/166
//   και ότι το email και η εφαρμογή δεν παρακολουθούνται 24 ώρες · 6. πώς επικοινωνεί αν κολλήσει · 7. να μη δίνει τον κωδικό.
// Δεν μπαίνουν ποτέ: κλινικές πληροφορίες, ονόματα θεραπευτών, στοιχεία άλλων μελών. Διατύπωση προς έγκριση από την υπεύθυνη.

const DAY = ["Κυριακή", "Δευτέρα", "Τρίτη", "Τετάρτη", "Πέμπτη", "Παρασκευή", "Σάββατο"];

export function welcomeEmail(p: {
  name: string; username: string; code: string; url: string;
  groups: { weekday: number; time: string }[]; contactEmail: string; appName?: string;
}): { subject: string; text: string } {
  const first = p.name.trim().split(/\s+/)[0] || p.name;
  const app = p.appName || "Apex";
  const groups = p.groups.length
    ? p.groups.map((g) => `${DAY[g.weekday] ?? ""} ${g.time}`).join(", ")
    : "θα τις δεις στο «Σήμερα»";
  const text = [
    `Γεια σου, ${first}.`,
    ``,
    `Καλώς ήρθες στο ${app}. Από εδώ και πέρα το πρόγραμμα, οι ατομικές σου και οι ομάδες είναι σε ένα μέρος, στο κινητό σου.`,
    ``,
    `Πώς μπαίνεις`,
    `Διεύθυνση: ${p.url || "(θα σου τη στείλει η ομάδα)"}`,
    `Όνομα χρήστη: ${p.username}`,
    `Προσωπικός κωδικός: ${p.code}`,
    `Στην πρώτη είσοδο θα σου ζητηθεί να βάλεις δικό σου κωδικό (τουλάχιστον 8 χαρακτήρες). Μην τον δώσεις σε κανέναν· η ομάδα δεν θα σου τον ζητήσει ποτέ.`,
    `Βάλε το ${app} στο κινητό σου σαν εφαρμογή, σε ένα λεπτό (βήματα για iPhone και Android): ${p.url ? `${p.url.replace(/\/login\/?$|\/$/, "")}/install` : "θα σου δείξουμε στην πρώτη ατομική"}`,
    ``,
    `Τα πρώτα σου βήματα`,
    `1. Μπες και δες το «Σήμερα»: εκεί είναι ό,τι έχεις κάθε μέρα.`,
    `2. Πριν την πρώτη σου ατομική, συμπλήρωσε τα στοιχεία σου (σου το ζητά το «Σήμερα»). Παίρνει 5 λεπτά.`,
    `3. Στην πρώτη ατομική θα κάνουμε μαζί το ιστορικό σου, με την ησυχία μας.`,
    `4. Οι ομάδες γίνονται ${groups}. Μπαίνεις πάντα από το κουμπί «Μπες στην ομάδα», για να ξέρει η ομάδα σου ότι ήρθες.`,
    `5. Κάθε βράδυ, αν θέλεις, γράφεις δυο λέξεις στο ημερολόγιο ανάκαμψης.`,
    ``,
    `Ποιος βλέπει τι`,
    `Ό,τι γράφεις στο ${app} το βλέπει μόνο η ομάδα σου (οι θεραπευτές σου και η διαχείριση). Κανείς άλλος. Τα στοιχεία σου μένουν κρυπτογραφημένα και σε διακομιστές στην Ευρώπη. Την πλήρη ενημέρωση για τα δεδομένα σου θα την πάρεις γραπτά πριν την πρώτη ατομική και μπορείς να ρωτήσεις ό,τι θέλεις.`,
    ``,
    `Αν δυσκολεύεσαι τώρα`,
    `Αν βρίσκεσαι σε άμεσο κίνδυνο, κάλεσε τώρα το 112 ή το 166. Το email και το ${app} δεν παρακολουθούνται σε εικοσιτετράωρη βάση. Μέσα στο ${app} υπάρχει το κόκκινο κουμπί, που σε πάει κατευθείαν στο πλάνο σου και στις γραμμές βοήθειας.`,
    ``,
    `Αν κάτι δεν δουλεύει ή ξέχασες τον κωδικό σου, γράψε μας στο ${p.contactEmail} και θα σου δώσουμε νέο.`,
    ``,
    `Χαιρόμαστε που είσαι εδώ. Ένα βήμα τη φορά.`,
    `Η ομάδα του ${app}`,
  ].join("\n");
  return { subject: `Καλώς ήρθες στο ${app} — τα στοιχεία εισόδου σου`, text };
}
