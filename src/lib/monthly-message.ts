const plural = (n: number, one: string, many: string) => `${n} ${n === 1 ? one : many}`;
const ORD = ["", "πρώτος", "δεύτερος", "τρίτος", "τέταρτος", "πέμπτος", "έκτος", "έβδομος", "όγδοος", "ένατος", "δέκατος"];
const list = (xs: string[]) => (xs.length <= 1 ? xs.join("") : `${xs.slice(0, -1).join(", ")} και ${xs.at(-1)}`);

export function themeLines(themes: string[]): string[] {
  const out: string[] = [];
  for (const t of themes) {
    const low = t.toLocaleLowerCase("el");
    const hit = THEME_LINES.find(([stem]) => low.includes(stem));
    if (hit && !out.includes(hit[1])) out.push(hit[1]);
  }
  return out.slice(0, 2);
}

export function draftMessage(firstName: string, p: Picture, month?: number): string {
  const lines: string[] = [];
  lines.push(month && ORD[month] ? `${firstName}, έκλεισε ο ${ORD[month]} μήνας σου μαζί μας — και θέλουμε να σου πούμε τι είδαμε.` : `${firstName}, έκλεισε ένας ακόμα μήνας σου μαζί μας — και θέλουμε να σου πούμε τι είδαμε.`);

  const themes = [...new Set(p.themes ?? [])];
  if (themes.length) {
    lines.push([`Αυτόν τον μήνα περάσαμε μαζί από ${themes.length === 1 ? "τη θεματική" : "τις θεματικές"} ${list(themes.map((t) => `«${t}»`))}.`, ...themeLines(themes)].join(" "));
  }

  const goalDays = p.weeks.reduce((s, w) => s + w.yes + w.partly, 0);
  if (p.weeks.length > 0) {
    const words = p.weeks.slice(0, 2).map((w) => `«${w.text}»`);
    lines.push(
      goalDays > 0
        ? `Έβαλες στον εαυτό σου στόχους με τα δικά σου λόγια — ${list(words)}. Κάθε μέρα που τους δούλεψες (${plural(goalDays, "μέρα", "μέρες")}) ήταν μια μικρή νίκη, μία μέρα τη φορά.`
        : `Έβαλες στον εαυτό σου στόχους με τα δικά σου λόγια — ${list(words)}. Το να ονομάζεις τι θέλεις να αλλάξεις είναι ήδη μεγάλο βήμα.`,
    );
  }

  const was: string[] = [];
  if (p.groups.came > 0) was.push(plural(p.groups.came, "ομάδα", "ομάδες"));
  if (p.sessions.came > 0) was.push(plural(p.sessions.came, "ατομική", "ατομικές"));
  if (was.length) lines.push(`Ήσουν εκεί: σε ${list(was)}. Ακόμα κι όταν δεν ήταν εύκολο, εμφανίστηκες για τον εαυτό σου — και αυτό μετράει.`);

  if (p.journal.written > 0) lines.push(`Τα ${plural(p.journal.written, "βράδυ", "βράδια")} που έγραψες απογραφές δείχνουν ότι θέλεις να κοιτάζεις τον εαυτό σου με ειλικρίνεια και φροντίδα.`);

  if (p.soberDays && p.soberDays > 0) lines.push(`${plural(p.soberDays, "μέρα", "μέρες")} νηφαλιότητας. Δεν είναι απλώς ένας αριθμός· είναι κάθε μέρα που επέλεξες τον εαυτό σου.`);

  lines.push("Η προσπάθειά σου φαίνεται, και χαιρόμαστε που περπατάμε δίπλα σου. Ο επόμενος μήνας σε περιμένει — συνεχίζουμε μαζί.");
  lines.push("Με εκτίμηση,\nη ομάδα του APEX");
  return lines.join("\n\n");
}
