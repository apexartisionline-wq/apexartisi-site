// Μήνυμα ενθάρρυνσης στο τέλος του «μήνα» (κύκλου). Μόνο θετικό πρόσημο και συναίσθημα: πόσο πάλεψε,
// δούλεψε, προσπάθησε — ποτέ τι δεν έκανε. Φτιάχνεται από πρότυπα φράσεων (όχι AI) με ό,τι δούλεψε
// (θεματικές του μήνα, οι στόχοι με τα δικά του λόγια, η παρουσία του)· το ελέγχει και το στέλνει η υπεύθυνη.

export type Picture = {
  sessions: { came: number; total: number };
  groups: { came: number; total: number };
  journal: { written: number; days: number };
  soberDays: number | null;
  weeks: { text: string; yes: number; partly: number }[];
  /** Οι θεματικές των εβδομάδων του μήνα (π.χ. «Πίστη», «Παράδοση»). */
  themes?: string[];
};

// Μία ζεστή φράση για κάθε θεματική που αναγνωρίζουμε (η ομάδα μπορεί να τις αλλάξει / συμπληρώσει).
