/** Κείμενο για αναζήτηση: πεζά, χωρίς τόνους (για να βρίσκει «απογραφες» και «Απογραφές»). */
export function normalizeSearch(s: string): string {
  return s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/ς/g, "σ");
}

export function entryText(e: GuideEntry): string {
  const t = (x: GuideText) => (Array.isArray(x) ? x.join(" ") : x);
  return [e.term, t(e.what), t(e.when), t(e.who), e.where.text].join(" ");
}
