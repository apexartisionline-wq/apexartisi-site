/**
 * Πλαίσιο πρωτοκόλλου στη σελίδα της 1ης ατομικής (υπεύθυνη 17/10: «να το δω απ' την αρχή, όταν μπαίνει ο θεραπευτής να κάνει
 * την πρώτη συνεδρία με βάση το πρωτόκολλο»). Από το docs/clinical/10 (πρόταση 16/10) με τις αποφάσεις της: η αρχική
 * αξιολόγηση μία και ολόκληρη στην 1η ατομική, χωρίς ρόλους. Τα επόμενα βήματα (πλάνο, ανασκόπηση) είναι ακόμα πρόταση.
 */
export function FirstSessionProtocol({ s0 }: { s0: { complete: boolean; missing: string[] } }) {
  return (
    <ol className="protocol" aria-label="Πρωτόκολλο αρχικών συνεδριών">
      <li className={s0.complete ? "done" : "warn"}>
        <span className="protocol-no">Σ0</span>
        <span><strong>Πριν την 1η ατομική</strong> — ενημέρωση, συναίνεση, συμφωνητικό, στοιχεία του μέλους.{" "}
          {s0.complete ? <span className="ok-text">✓ Ολοκληρώθηκε</span> : <span className="warn-text">Λείπουν: {s0.missing.join(", ")} — το μέλος μπορεί να μπει, αλλά η διαχείριση το κλείνει.</span>}
        </span>
      </li>
      <li className="now">
        <span className="protocol-no">Σ1</span>
        <span><strong>Σήμερα: υποδοχή και αρχική αξιολόγηση</strong> — το ιστορικό, μία και ολόκληρη (~40′), από εσένα. Ξεκινάς με «Γιατί τώρα;», κλείνεις με δυνάμεις, φόβους και τη σύνοψη για την ομάδα. «Ολοκλήρωση» κλείνει και την ατομική.</span>
      </li>
      <li>
        <span className="protocol-no">Μετά</span>
        <span>Πλάνο υποστήριξης μέσα στις 2 πρώτες εβδομάδες · πρώτη ανασκόπηση στην 4η ατομική. Πάντα σε ατομική, όχι σε Therapair. <span className="muted">(πρόταση 16/10, προς έγκριση)</span></span>
      </li>
    </ol>
  );
}
