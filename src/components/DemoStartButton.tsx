"use client";

import { useFormStatus } from "react-dom";

// «Ξεκίνα δοκιμαστική ατομική τώρα» (14/10): δείχνει ότι δουλεύει όσο φτιάχνεται η ατομική, και δεν ξαναπατιέται στο μεταξύ.
// second: το μικρό όνομα του ψεύτικου μέλους που ολοκλήρωσε το ιστορικό → «Δοκιμαστική 2η ατομική (πλάνο υποστήριξης)» (17/10).
export function DemoStartButton({ first = false, second }: { first?: boolean; second?: string }) {
  const { pending } = useFormStatus();
  const title = second
    ? `Η 2η ατομική με το ψεύτικο μέλος ${second} σε 2 λεπτά: ανοίγει με το πλάνο υποστήριξης στη θέση του σημειώματος`
    : first ? "Φτιάχνει νέο ψεύτικο μέλος χωρίς ιστορικό και την 1η του ατομική σε 2 λεπτά (με αρχική αξιολόγηση)" : "Φτιάχνει μια ατομική σε 2 λεπτά με ψεύτικο μέλος, για να δεις πώς συνδέεσαι και τι βλέπεις μέσα στην ατομική";
  return (
    <button type="submit" className={first || second ? "sm outline" : "sm"} disabled={pending} aria-busy={pending} title={title}>
      {pending ? "Φτιάχνεται η δοκιμαστική ατομική…" : second ? `Δοκιμαστική 2η ατομική (πλάνο υποστήριξης, ${second})` : first ? "Δοκιμαστική 1η ατομική (νέο μέλος)" : "Ξεκίνα δοκιμαστική ατομική τώρα"}
    </button>
  );
}
