// Σημείωμα ως κείμενο, με έντονους τους τίτλους των ενοτήτων («Τι έφερε:», «Πώς παρουσιάστηκε:»…)
// για να σαρώνεται εύκολα με το μάτι, ειδικά στο κινητό. Μόνο γνωστοί τίτλοι γίνονται έντονοι.
const LABELS = [
  "Πώς παρουσιάστηκε", "Διάθεση", "Πόσο βοηθά τον εαυτό του/της", "Πώς νιώθει στη διαδικασία", "Τι έφερε",
  "Σε τι επικεντρώθηκε η παρέμβαση", "Ανταπόκριση και άμυνες", "Τα θετικά", "Γράφει απογραφές", "Πώς ήταν να είμαι μαζί του/της",
  "Τι προτείναμε", "Ανησυχία για την ασφάλεια", "Προβληματισμός προς τη θεραπευτική ομάδα", "Τι έγινε / τι κάνουμε",
  "Συνδέθηκε με το άλλο μέλος", "Δέχτηκε βοήθεια", "Στάση", "Τι εμφανίστηκε", "Τι βγήκε από την κουβέντα",
];

export function NoteText({ text, style }: { text: string; style?: React.CSSProperties }) {
  return (
    <div className="body-text note-text" style={style}>
      {text.split("\n").map((line, i) => {
        const label = LABELS.find((l) => line.startsWith(`${l}:`));
        return (
          <div key={i}>
            {label ? <><strong>{label}:</strong>{line.slice(label.length + 1)}</> : line || " "}
          </div>
        );
      })}
    </div>
  );
}
